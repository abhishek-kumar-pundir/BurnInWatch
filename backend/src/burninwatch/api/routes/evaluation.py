"""Offline model evaluation: static research artifacts, clearly separate from live screening."""
from __future__ import annotations

import json

from fastapi import APIRouter, Depends

from ...config import Settings
from ...errors import BurnInWatchError
from ...schemas.details import OfflineEvaluationResponse
from ..deps import get_settings

router = APIRouter(tags=["evaluation"])


@router.get("/evaluation", response_model=OfflineEvaluationResponse)
def offline_evaluation(settings: Settings = Depends(get_settings)) -> OfflineEvaluationResponse:
    """Offline evaluation of the trained models on the research dataset (NOT a live result).

    Generated by ``scripts/build_offline_evaluation.py`` from the research artifacts; only
    metrics that exist there are present - unavailable ones are listed with the reason.
    """
    path = settings.evaluation_file
    if not path.is_file():
        raise BurnInWatchError(
            "Offline evaluation file not found. Run scripts/build_offline_evaluation.py.",
            code="EVALUATION_UNAVAILABLE", status_code=404, details={"expected": path.name},
        )
    return OfflineEvaluationResponse(**json.loads(path.read_text(encoding="utf-8")))
